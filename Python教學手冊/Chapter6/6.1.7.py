lst = [[17, 21], [98, 12], [33, [44, [21, 38, 35]]], [35, 42]]

#Shift + Alt + 方向鍵(上/下) ==>複製該行至上或下
print(f"a = {lst[0]}")
print(f"b = {lst[0][1]}")
print(f"c = {lst[2][0]}")
print(f"d = {lst[3]}")
print(f"e = {lst[1][0]}")
print(f"f = {lst[2][1][0]}")
print(f"g = {lst[2][1][1]}")
print(f"h = {lst[2][1][1][1:]}")
print(f"i = {lst[2][1][1][0:2]}")
print(f"j = {lst[2][1][1][1]}")
print(f"k = {lst[0:2]}")
print(f"l = {lst[2][1]}")